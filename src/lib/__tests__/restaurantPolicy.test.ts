import { resolveDay } from "../workHours";
import { publicHolidays } from "../holidays";
import { staffingWindows } from "../staffing";
import { boundaryRestDays } from "../scheduler";
import type { Shift } from "../../types";
import { describe, it, expect } from "vitest";
import { compareStaffingPriority, isOptionalCoverageTime, RESTAURANT_POLICY } from "../restaurantPolicy";
import { applyReportedHistory } from "../history";
import { createSampleSchedule } from "../sampleData";
describe("An Sushibar policy",()=>{
 it("migrates all saved minijobs to service once, preserving other roles and contracts",()=>{
  const schedule=createSampleSchedule(); schedule.historyVersion=3;
  schedule.employees[4].workRole="BOTH";
  schedule.employees[5].workRole="KITCHEN";
  const migrated=applyReportedHistory(schedule);
  expect(migrated.historyVersion).toBe(6);
  expect(migrated.employees.slice(4).map(e=>e.workRole)).toEqual(["SERVICE_SUSHI","SERVICE_SUSHI"]);
  expect(migrated.employees.slice(0,4)).toEqual(schedule.employees.slice(0,4));
  expect(migrated.employees.slice(4).map(e=>e.targetMinutes)).toEqual([1200,1200]);
  expect(applyReportedHistory(migrated)).toBe(migrated);
 });
 it("updates old 43h defaults once, preserves custom hours and historical months",()=>{
  const schedule=createSampleSchedule();schedule.historyVersion=4;
  schedule.employees[4].targetMinutes=2580;
  schedule.employees[4].payrollRecords=[{month:"2026-09",convertedHours:43},{month:"2026-10",convertedHours:43}];
  schedule.employees[5].targetMinutes=900;
  const migrated=applyReportedHistory(schedule);
  expect(migrated.employees[4].targetMinutes).toBe(1200);
  expect(migrated.employees[4].payrollRecords).toEqual([{month:"2026-09",convertedHours:43}]);
  expect(migrated.employees[5].targetMinutes).toBe(900);
  expect(applyReportedHistory(migrated)).toBe(migrated);
 });
 it("reserves rest across both month boundaries without reopening blocked days",()=>{
  const schedule = createSampleSchedule();
  const employee = schedule.employees[0];
  const adjacentShifts = [24,25,26,27,28,29,30].map(day => ({ employeeId:employee.id,date:`2026-09-${day}` } as Shift));
  adjacentShifts.push({employeeId:employee.id,date:"2026-11-01"} as Shift);
  const blocked = boundaryRestDays({year:2026,month:10,workHours:schedule.workHours,employees:[employee],adjacentShifts,blockedDays:{[employee.id]:["2026-10-15"]}});
  expect(blocked[employee.id]).toContain("2026-10-01");
  expect(blocked[employee.id]).toContain("2026-10-26");
  expect(blocked[employee.id]).toContain("2026-10-15");
 });
 it("keeps afternoon coverage as a fallback after other opening slots",()=>{
  expect(isOptionalCoverageTime(839)).toBe(false);
  expect(isOptionalCoverageTime(840)).toBe(true);
  expect(isOptionalCoverageTime(959)).toBe(true);
  expect(isOptionalCoverageTime(960)).toBe(false);
  for(const weekday of RESTAURANT_POLICY.peak.weekdays){
   const windows=staffingWindows([{startMinutes:630,endMinutes:1260}],weekday);
   // 14:00–16:00 được phép trống: rule 2 người chỉ phủ hai khung còn lại.
   expect(windows.filter(w=>w.minStaff===2).map(w=>[w.startMinutes,w.endMinutes])).toEqual([[630,840],[960,1260]]);
  }
 });
 it("protects other opening slots, then afternoon coverage, before soft peaks",()=>{
  expect(compareStaffingPriority([0,100,100,100],[1,0,0,0])).toBeLessThan(0);
  expect(compareStaffingPriority([0,0,100,100],[0,1,0,0])).toBeLessThan(0);
  expect(compareStaffingPriority([0,0,0,100],[0,0,1,0])).toBeLessThan(0);
  expect(compareStaffingPriority([0,0,0,1],[0,0,0,2])).toBeLessThan(0);
  expect(compareStaffingPriority([1,2,3,4],[1,2,3,4])).toBe(0);
 });
 it("has the evening peak every day",()=>{
  for (const weekday of RESTAURANT_POLICY.peak.weekdays) {
    expect(staffingWindows([{startMinutes:630,endMinutes:1260}],weekday).some(w=>w.startMinutes===1020 && w.endMinutes===1170 && w.minStaff===3)).toBe(true);
  }
  expect(RESTAURANT_POLICY.peak).toEqual({startMinutes:1020,endMinutes:1170,weekdays:["monday","tuesday","wednesday","thursday","friday","saturday","sunday"]});
 });
 it("removes autogenerated minijob-only peak preferences, preserves custom ones",()=>{
  const schedule=createSampleSchedule(); schedule.historyVersion=2;
  schedule.employees[4].preferredWindows=[{days:["friday","saturday","sunday"],startMinutes:1050,endMinutes:1170}];
  schedule.employees[5].preferredWindows=[{days:["friday"],startMinutes:900,endMinutes:1260}];
  const migrated=applyReportedHistory(schedule);
  expect(migrated.employees[4].preferredWindows).toBeUndefined();
  expect(migrated.employees[5].preferredWindows).toEqual(schedule.employees[5].preferredWindows);
 });
});

it("opens holidays once for saved stores, preserves later preferences and date closures",()=>{
 const schedule=createSampleSchedule();schedule.historyVersion=5;schedule.workHours.holidayClosed=true;
 const migrated=applyReportedHistory(schedule);
 expect(migrated.workHours.holidayClosed).toBe(false);
 expect(resolveDay(migrated.workHours,"2026-10-03",publicHolidays(2026)).closed).toBe(false);
 expect(resolveDay(migrated.workHours,"2026-10-03",publicHolidays(2026),{"2026-10-03":{date:"2026-10-03",closed:true}}).closed).toBe(true);
 const custom={...migrated,workHours:{...migrated.workHours,holidayClosed:true}};
 expect(applyReportedHistory(custom)).toBe(custom);
});
